export function getInitialLocale(): Locale {
  const saved = localStorage.getItem("nexus.locale");
  if (saved === "zh-CN" || saved === "en-US") {
    return saved;
  }

  return navigator.language.toLowerCase().startsWith("zh")
    ? "zh-CN"
    : "en-US";
}
